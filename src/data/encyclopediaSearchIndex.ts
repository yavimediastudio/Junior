/**
 * Normaliza un texto removiendo acentos y convirtiendo a minúsculas para búsqueda tolerante
 */
export function normalizeSearchTerm(term: string): string {
  return term
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();
}

/**
 * Busca elementos en la enciclopedia según el término ingresado
 */
export function searchEncyclopedia(query: string): EncyclopediaSearchItem[] {
  const cleanQuery = normalizeSearchTerm(query);
  if (!cleanQuery) return [];

  const queryWords = cleanQuery.split(/\s+/).filter(Boolean);

  return ENCYCLOPEDIA_SEARCH_ITEMS.map((item) => {
    let score = 0;
    const cleanTitle = normalizeSearchTerm(item.title);
    const cleanSubtitle = normalizeSearchTerm(item.subtitle);
    const cleanModule = normalizeSearchTerm(item.moduleName);
    const cleanKeywords = item.keywords.map(normalizeSearchTerm);

    // Exact matches
    if (cleanTitle === cleanQuery) score += 100;
    if (cleanTitle.startsWith(cleanQuery)) score += 60;
    if (cleanTitle.includes(cleanQuery)) score += 40;

    // Check each query word
    for (const word of queryWords) {
      if (cleanTitle.includes(word)) score += 20;
      if (cleanKeywords.some((k) => k.includes(word))) score += 15;
      if (cleanSubtitle.includes(word)) score += 8;
      if (cleanModule.includes(word)) score += 10;
    }

    return { item, score };
  })
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((entry) => entry.item);
}
